const assert = require('node:assert/strict')
const {load, fakeTime} = require('./helpers/platform-fixture.cjs')
function fixture(debug = false) {
  const {createScenarioRunner} = load('platform/core/scenario-runner.js')
  const {createGameClock} = load('platform/core/game-clock.js')
  const {createMechanicRegistry} = load('platform/core/mechanic-registry.js')
  const {scanMechanic} = load('platform/modules/mechanics/scan.js')
  const {discoverMechanic} = load('platform/modules/mechanics/discover.js')
  const {sequenceMechanic} = load('platform/modules/mechanics/sequence.js')
  const {chooseMechanic} = load('platform/modules/mechanics/choose.js')
  const {collectMechanic} = load('platform/modules/mechanics/collect.js')
  const {touchMechanic} = load('platform/modules/mechanics/touch.js')
  const {nullEscapeScenario} = load('games/pixel-quest/episodes/null-escape/scenario.js')
  const {objects} = load('games/pixel-quest/episodes/null-escape/objects.js')
  const time = fakeTime()
  const runner = createScenarioRunner({gameId:'pixel-quest', scenario:nullEscapeScenario,
    registry:createMechanicRegistry([scanMechanic,touchMechanic,discoverMechanic,collectMechanic,chooseMechanic,sequenceMechanic]), clock:createGameClock(time), debug,
    capabilities:['markerInput','objectTouch','targetVisibility','sequencePresentation'], markerIds:['START_MARKER'], objectIds:Object.keys(objects),hintIds:['scan','button','search_listen','search_direction','search_highlight','collect_help','collect_highlight','choose_rule','choose_watch','sequence_help']})
  const events=[]; runner.on('*',e=>events.push(e))
  const scan=()=>runner.input('ar.marker_detected',{marker_id:'START_MARKER'})
  const touch=()=>runner.input('input.target_touched',{target_id:'red_button',interaction_id:'tap-'+events.length})
  return {runner,time,events,scan,touch}
}
function finishCollection(runner,time) {
  assert.equal(runner.getSnapshot().step_id,'collect_parts')
  time.advance(12000)
  for(const id of ['null_body','null_right_arm','null_left_arm']) {
    runner.input('input.target_touched',{target_id:id,interaction_id:id})
  }
  assert.equal(runner.getSnapshot().scene_phase,'PRESENTING')
  time.advance(8000)
}
function finishChoice(runner,time) {
  assert.equal(runner.getSnapshot().step_id,'choose_core')
  time.advance(11200)
  runner.input('input.target_touched',{target_id:'core_01',interaction_id:'wrong-core'})
  runner.input('input.target_touched',{target_id:'core_03',interaction_id:'correct-core'})
  time.advance(5000)
}
function finishSequence(runner,time) {
  assert.equal(runner.getSnapshot().step_id,'portal_sequence');time.advance(5000)
  const token=runner.getSnapshot().mechanic.state.presentation_token
  runner.input('presentation.sequence_finished',{token})
  for(const id of ['symbol_diamond','symbol_triangle','symbol_circle'])runner.input('input.target_touched',{target_id:id,interaction_id:id})
  time.advance(6000)
}
test('Null Escape gates TOUCH until all warnings and starts DISCOVER only after accident and completes all six mechanics',()=>{
  const {runner,time,events,scan,touch}=fixture()
  assert.equal(runner.getSnapshot().status,'READY')
  runner.start(); scan(); touch()
  assert.equal(runner.getSnapshot().scene_phase,'PREPARING')
  time.advance(9699); touch(); assert.equal(runner.getSnapshot().mechanic.progress.current,0)
  time.advance(1); assert.equal(runner.getSnapshot().scene_phase,'ACTIVE')
  touch(); touch(); assert.equal(runner.getSnapshot().scene_phase,'PRESENTING')
  time.advance(13099); assert.equal(runner.getSnapshot().status,'ACTIVE')
  time.advance(1); assert.equal(runner.getSnapshot().step_id,'discover_null')
  runner.input('ar.target_found',{target_id:'null_head',observed_ms:500})
  assert.equal(runner.getSnapshot().scene_phase,'PREPARING')
  time.advance(7400)
  runner.input('ar.target_found',{target_id:'null_head',observed_ms:500})
  time.advance(5300)
  finishCollection(runner,time)
  finishChoice(runner,time)
  finishSequence(runner,time)
  time.advance(load('games/pixel-quest/episodes/null-escape/finale-config.js').finaleDuration)
  assert.equal(runner.getSnapshot().status,'COMPLETE')
  assert.equal(runner.getSnapshot().scenario_state,'COMPLETED')
  assert.equal(events.filter(e=>e.type==='scene.mechanic_completed').length,5)
  assert.equal(events.filter(e=>e.type==='scenario.completed').length,1)
  assert.equal(runner.getSnapshot().history.length,7)
  runner.retryCurrent();assert.equal(runner.getSnapshot().history.length,6)
  assert.equal(runner.getSnapshot().step_id,'portal_finale')
  runner.dispose(); assert.equal(time.pending(),0)
})
