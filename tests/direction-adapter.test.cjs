const test=require('node:test')
const assert=require('node:assert/strict')
const {load}=require('./helpers/platform-fixture.cjs')
const {directionForTarget:direction}=load('platform/ar/direction-adapter.js')
test('guidance points toward offscreen targets, handles rear projection and invalid observations',()=>{
 assert.equal(direction({x:0,y:0},{x:0,z:-1}),'center')
 assert.equal(direction({x:-2,y:0},{x:-1,z:-1}),'left')
 assert.equal(direction({x:2,y:0},{x:1,z:-1}),'right')
 assert.equal(direction({x:0,y:2},{x:0,z:-1}),'up')
 assert.equal(direction({x:0,y:-2},{x:0,z:-1}),'down')
 assert.equal(direction({x:-2,y:0},{x:1,z:1}),'right')
 assert.equal(direction({x:2,y:0},{x:-1,z:1}),'left')
 assert.equal(direction({x:NaN,y:0},{x:0,z:-1}),'unavailable')
})
