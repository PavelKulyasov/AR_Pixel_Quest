const test = require('node:test')
const assert = require('node:assert/strict')
const {fixture, step} = require('./helpers/platform-fixture.cjs')
test('two configured SCAN steps advance in order, complete once and preserve history', () => {
  let completed = 0
  const f = fixture([step('a', 'marker-a', {advance: 'auto', next: {success: 'b', fail: null}}), step('b', 'marker-b')], {onComplete: () => completed++})
  f.runner.start(); f.runner.start()
  f.runner.input('ar.marker_detected', {marker_id: 'marker-a'})
  assert.equal(f.runner.getSnapshot().step_id, 'b')
  f.runner.input('ar.marker_detected', {marker_id: 'marker-b'})
  assert.equal(f.runner.getSnapshot().status, 'AWAITING_NEXT')
  f.runner.next(); f.runner.next()
  assert.equal(completed, 1); assert.equal(f.runner.getSnapshot().status, 'COMPLETE')
  assert.equal(f.runner.getSnapshot().history.length, 2)
  f.runner.dispose()
})
test('restart isolates old-run events and separate sessions', () => {
  const a = fixture(); const b = fixture()
  a.runner.start(); b.runner.start()
  const old = a.runner.createInput('ar.marker_detected', {marker_id: 'marker-a'})
  assert.equal(b.runner.dispatch(old), false)
  a.runner.restart(); assert.equal(a.runner.dispatch(old), false)
  const current = a.runner.createInput('ar.marker_detected', {marker_id: 'marker-a'})
  assert.equal(a.runner.dispatch(current), true)
  assert.equal(a.runner.dispatch(current), false)
  assert.equal(b.runner.getSnapshot().status, 'ACTIVE')
  a.runner.dispose(); b.runner.dispose()
})
test('pause blocks input and freezes hints/timeouts, timeout follows explicit failure branch', () => {
  const f = fixture([
    step('a', 'marker-a', {parameters: {time_limit: 100}, hints: [{after_ms: 30, content_id: 'look'}], advance: 'auto', next: {success: null, fail: 'b'}}),
    step('b', 'marker-b'),
  ])
  f.runner.start(); f.time.advance(20); f.runner.pause(); f.time.advance(1000)
  assert.equal(f.runner.input('ar.marker_detected', {marker_id: 'marker-a'}), false)
  assert.equal(f.events.filter(e => e.type === 'mechanic.hint').length, 0)
  f.runner.resume(); f.time.advance(10)
  assert.equal(f.events.filter(e => e.type === 'mechanic.hint').length, 1)
  f.time.advance(70); assert.equal(f.runner.getSnapshot().step_id, 'b')
  assert.equal(f.runner.getSnapshot().history[0].outcome, 'FAIL')
  f.runner.dispose(); assert.equal(f.time.pending(), 0)
})
test('critical handlers abort with cleanup, observer failures cannot break the scenario', () => {
  const a = fixture(); a.runner.on('mechanic.started', () => {throw new Error('presentation failed')})
  a.runner.start(); assert.equal(a.runner.getSnapshot().status, 'ERROR'); assert.equal(a.time.pending(), 0)
  a.runner.dispose()
  const b = fixture(); b.runner.on('*', () => {throw new Error('analytics offline')}, {critical: false})
  b.runner.start(); b.runner.input('ar.marker_detected', {marker_id: 'marker-a'}); b.runner.next()
  assert.equal(b.runner.getSnapshot().status, 'COMPLETE'); b.runner.dispose()
})
test('invalid graphs are rejected before start', () => {
  assert.throws(() => fixture([step('a', 'marker-a', {next: {success: 'missing', fail: null}})]), /Unknown next/)
  assert.throws(() => fixture([step('a', 'marker-a', {next: {success: 'a', fail: null}})]), /cycles/)
  assert.throws(() => fixture([step('a'), step('a')]), /Duplicate/)
  assert.throws(() => fixture([step('a'), step('b')]), /unreachable/)
})

test('invalid input data aborts cleanly and old hint timers do not survive restart', () => {
  const invalid = fixture(); invalid.runner.start()
  assert.equal(invalid.runner.input('ar.marker_detected', {marker_id: 'marker-a', invalid: NaN}), false)
  assert.equal(invalid.runner.getSnapshot().status, 'ERROR')
  invalid.runner.dispose()
  const f = fixture([step('a', 'marker-a', {hints: [{after_ms: 100, content_id: 'look'}]})])
  f.runner.start(); f.time.advance(50); f.runner.restart()
  const run = f.runner.getSnapshot().run_id
  f.time.advance(50)
  assert.equal(f.events.filter(e => e.type === 'mechanic.hint').length, 0)
  f.time.advance(50)
  assert.equal(f.events.filter(e => e.type === 'mechanic.hint').length, 1)
  assert.equal(f.events.find(e => e.type === 'mechanic.hint').run_id, run)
  f.runner.dispose()
})
