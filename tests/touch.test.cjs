const test = require('node:test')
const assert = require('node:assert/strict')
const {load, fixture, step} = require('./helpers/platform-fixture.cjs')
const {touchMechanic} = load('platform/modules/mechanics/touch.js')
const {createMechanicRegistry} = load('platform/core/mechanic-registry.js')
const config = id => step('touch', null, {mechanic_id: 'AR-03', mechanic: 'TOUCH', content: {target_id: id}, parameters: {time_limit: null}, success_condition: {metric: 'target_touched', op: 'eq', value: true}})
const setup = (id = 'terminal', parameters = {}) => fixture([{...config(id), parameters}], {registry: createMechanicRegistry([touchMechanic]), capabilities: ['objectTouch'], objectIds: [id]})
test('TOUCH accepts only its target and an interaction ID; feedback and completion happen once', () => {
  for (const id of ['terminal', 'unrelated_artifact']) {
    const {runner, events} = setup(id); runner.start()
    for (const payload of [{target_id: 'wrong', interaction_id: 'tap'}, {target_id: id}, {target_id: id, interaction_id: ' '}]) runner.input('input.target_touched', payload)
    assert.equal(runner.getSnapshot().status, 'ACTIVE')
    runner.input('input.target_touched', {target_id: id, interaction_id: 'tap'})
    runner.input('input.target_touched', {target_id: id, interaction_id: 'tap'})
    assert.equal(runner.getSnapshot().status, 'AWAITING_NEXT')
    assert.equal(events.filter(e => e.type === 'mechanic.feedback').length, 1)
    assert.equal(events.filter(e => e.type === 'mechanic.completed').length, 1)
    runner.dispose()
  }
})
test('TOUCH blocks paused, stale and disposed input; timeout remains a failure', () => {
  const {runner, time} = setup('terminal', {time_limit: 100})
  runner.start()
  const old = runner.createInput('input.target_touched', {target_id: 'terminal', interaction_id: 'tap'})
  runner.pause(); runner.dispatch(old); time.advance(200)
  assert.equal(runner.getSnapshot().status, 'ACTIVE')
  runner.resume(); runner.restart(); runner.dispatch(old)
  assert.equal(runner.getSnapshot().status, 'ACTIVE')
  time.advance(100)
  assert.equal(runner.getSnapshot().outcome, 'FAIL')
  runner.dispose(); assert.equal(runner.dispatch(old), false)
})
test('TOUCH validates target, capability and success condition', () => {
  const registry = createMechanicRegistry([touchMechanic])
  const env = {capabilities: ['objectTouch'], objectIds: ['terminal'], hintIds: []}
  assert.throws(() => registry.validateStep(config('unknown'), env))
  assert.throws(() => registry.validateStep(config('terminal'), {...env, capabilities: []}))
  assert.throws(() => registry.validateStep({...config('terminal'), success_condition: {metric: 'target_touched', op: 'eq', value: false}}, env))
})
