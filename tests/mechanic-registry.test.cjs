const test = require('node:test')
const assert = require('node:assert/strict')
const {load, step, environment} = require('./helpers/platform-fixture.cjs')
const {createMechanicRegistry} = load('platform/core/mechanic-registry.js')
const {scanMechanic} = load('platform/modules/mechanics/scan.js')
const {mechanicCatalog} = load('platform/modules/mechanics/catalog.js')
test('catalog has 20 unique canonical types; unimplemented types cannot execute', () => {
  assert.equal(mechanicCatalog.length, 20)
  assert.equal(new Set(mechanicCatalog.map(m => m.mechanic_id)).size, 20)
  const registry = createMechanicRegistry([scanMechanic])
  assert.throws(() => registry.validateStep(step('s', 'marker-a', {mechanic_id: 'AR-02', mechanic: 'DISCOVER'}), environment), /not implemented/)
  assert.throws(() => createMechanicRegistry([scanMechanic, scanMechanic]), /Duplicate/)
  assert.throws(() => createMechanicRegistry([{...scanMechanic, mechanic: 'COLLECT'}]), /canonical/)
})
test('registry rejects mismatched names, missing adapters, foreign content and invalid rules', () => {
  const registry = createMechanicRegistry([scanMechanic])
  assert.throws(() => registry.validateStep(step('s', 'marker-a', {mechanic: 'TOUCH'}), environment), /mismatch/)
  assert.throws(() => registry.validateStep(step(), {...environment, capabilities: []}), /capability/)
  assert.throws(() => registry.validateStep(step('s', 'wrong'), environment), /marker/)
  assert.throws(() => registry.validateStep(step('s', 'marker-a', {parameters: {time_limit: -1}}), environment), /time_limit/)
  assert.throws(() => registry.validateStep(step('s', 'marker-a', {success_condition: {metric: 'marker_detected', op: 'eq', value: false}}), environment), /success/)
  assert.throws(() => registry.validateStep(step('s', 'marker-a', {hints: [{after_ms: 0, content_id: 'missing'}]}), environment), /hint/)
})
