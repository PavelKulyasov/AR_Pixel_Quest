const test = require('node:test')
const assert = require('node:assert/strict')
const {load, fixture, step} = require('./helpers/platform-fixture.cjs')
const {discoverMechanic} = load('platform/modules/mechanics/discover.js')
const {createMechanicRegistry} = load('platform/core/mechanic-registry.js')
const config = () => step('discover', null, {mechanic_id: 'AR-02', mechanic: 'DISCOVER', content: {target_id: 'terminal'}, parameters: {hold_ms: 500}, success_condition: {metric: 'target_found', op: 'eq', value: true}})
const setup = () => fixture([config()], {registry: createMechanicRegistry([discoverMechanic]), capabilities: ['targetVisibility']})
test('DISCOVER rejects wrong target, short and invalid duration; completes once', () => {
  const {runner, events} = setup(); runner.start()
  for (const payload of [{target_id: 'other', observed_ms: 500}, {target_id: 'terminal', observed_ms: 499}, {target_id: 'terminal', observed_ms: -1}]) runner.input('ar.target_found', payload)
  assert.equal(runner.getSnapshot().status, 'ACTIVE')
  runner.input('ar.target_found', {target_id: 'terminal', observed_ms: 500})
  runner.input('ar.target_found', {target_id: 'terminal', observed_ms: 600})
  assert.equal(runner.getSnapshot().status, 'AWAITING_NEXT')
  assert.equal(events.filter(e => e.type === 'mechanic.completed').length, 1)
  runner.dispose()
})
test('DISCOVER restart rejects stale confirmation and hidden input', () => {
  const {runner} = setup(); runner.start()
  const old = runner.createInput('ar.target_found', {target_id: 'terminal', observed_ms: 500})
  runner.restart(); runner.dispatch(old)
  runner.pause(); runner.input('ar.target_found', old.payload)
  assert.equal(runner.getSnapshot().status, 'ACTIVE')
  runner.resume(); runner.input('ar.target_found', old.payload)
  assert.equal(runner.getSnapshot().status, 'AWAITING_NEXT'); runner.dispose()
})
test('DISCOVER validates target, capability and observation parameters', () => {
  const registry = createMechanicRegistry([discoverMechanic])
  const env = {capabilities: ['targetVisibility'], objectIds: ['terminal'], hintIds: []}
  for (const parameters of [{hold_ms: 0}, {hold_ms: Infinity}, {search_radius: 0}, {search_radius: 2}]) assert.throws(() => registry.validateStep({...config(), parameters}, env))
  assert.throws(() => registry.validateStep(config(), {...env, objectIds: []}))
  assert.throws(() => registry.validateStep(config(), {...env, capabilities: []}))
})
